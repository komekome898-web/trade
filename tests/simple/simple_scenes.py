def ts(k):
    """足 k の始まり。2023-11-14T00:00 から 1 分ずつ。"""
    return f"2023-11-14T{k // 60:02d}:{k % 60:02d}:00+00:00"


def make_bars(rows, minutes=None):
    minutes = minutes or list(range(len(rows)))
    return [(ts(m),) + tuple(float(x) for x in r) + (1.0,) for m, r in zip(minutes, rows)]


class Script:
    """足 k の判定で plan[k] の注文を返す。約定し終えた番号は返さない(raw なら返す)。届いた約定の番号を残す。"""

    def __init__(self, plan, signals=None, raw=False):
        self.plan, self.signals, self.raw, self.k, self.seen, self.done = plan, signals or {}, raw, -1, [], set()

    def decide(self, bar, fills):
        self.k += 1
        self.seen.append([f["id"] for f in fills])
        self.done |= {f["id"] for f in fills}
        orders = {i: o for i, o in self.plan.get(self.k, {}).items() if self.raw or i not in self.done}
        return orders, list(self.signals.get(self.k, []))


def table(out, name, side):
    with open(os.path.join(out, f"{name}_{side}.csv"), newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def check_all(cases, fn):
    """cases の全部に fn を当て、落ちた場面の名前と理由を全部集めてから 1 回で落とす(1 つの試験で表を回す)。"""
    bad = []
    for case in cases:
        try:
            fn(case)
        except (Exception, pytest.fail.Exception) as e:  # 例外で止まった場面も、残りの場面を回してから一緒に出す
            bad.append(f"{case['name'] if isinstance(case, dict) else case[0]}: {type(e).__name__}: {e}")
    assert not bad, f"{len(bad)} / {len(cases)} の場面が落ちた:\n" + "\n".join(bad)


