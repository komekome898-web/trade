def _bars(rows, minutes=None):
    """(始値, 高値, 安値, 終値[, 出来高])の並び → 道に渡す足(出来高の既定は 1)。"""
    minutes = minutes or list(range(len(rows)))
    return [(ts(m),) + tuple(float(x) for x in r[:4]) + (float(r[4]) if len(r) > 4 else 1.0,) for m, r in zip(minutes, rows)]


def _side(x, side):
    return x[side] if isinstance(x, dict) else x


def _outcome(out, side, idx):
    with open(os.path.join(out, f"orders_{side}.csv"), newline="", encoding="utf-8") as fh:
        od = list(csv.DictReader(fh))
    by = {r["id"]: r for r in od}

    def key(r):
        return r["form"], r["px_calc"] or r["offset"]
    orders = sorted((r["form"], r["side"], r["qty"], r["px_calc"] or r["offset"], r["close"], idx.get(r["from_ts"]),
                     idx.get(r["to_ts"]), key(by[r["root"] or r["parent"]]) if (r["root"] or r["parent"]) else None)
                    for r in od)
    with open(os.path.join(out, f"fills_{side}.csv"), newline="", encoding="utf-8") as fh:
        fills = sorted((idx[r["ts"]], r["side"], r["qty"], r["px"], r["case"]) for r in csv.DictReader(fh))
    with open(os.path.join(out, f"signals_{side}.csv"), newline="", encoding="utf-8") as fh:
        sig = list(csv.DictReader(fh))
    return orders, fills, sig


def test_scenes(tmp_path):
    def one(sc):
        bars = _bars(sc["rows"], sc.get("minutes"))
        idx = {b[0]: i for i, b in enumerate(bars)}
        for side in SIDES:
            out = str(tmp_path / f"{SCENES.index(sc)}" / side)
            run(bars, MatildaSimple(sc["params"]), side=side, out_dir=out, tick=1.0, meta=META)
            orders, fills, sig = _outcome(out, side, idx)
            assert orders == _side(sc["orders"], side), (side, "orders", orders)
            assert fills == _side(sc["fills"], side), (side, "fills", fills)
            got = [(r["id"], r["kind"], r["direction"], idx.get(r["start_ts"]), idx.get(r["end_ts"]), r["end_reason"])
                   for r in sig]
            assert got == sc["signals"], (side, "signals", got)
            for k, want in sc.get("values", {}).items():
                v = json.loads(next(r["value_json"] for r in sig if r["id"] == "e1"))
                assert v[k] == pytest.approx(want), (side, k, v[k])
            # 戦略の注文は道の止める注文に当たらず、約定の作り直しと数の作り直しが合う
            assert refill(bars, out, side) == [], side
            assert check_numbers(out, side) == [], side
    check_all(SCENES, one)
