"""Shared helpers for the bar reference tests (bot.bt.reference.bar_sim)."""
from __future__ import annotations

from fractions import Fraction as F

from bot.bt.reference.bar_sim import run_bars


def X(v) -> F:
    """Exact decimal value of a written number."""
    return F(str(v))


def opts(**kw) -> dict:
    """Every option spelled out. The values below are the scene book's
    'nothing switched on' values (capital 6000, order amount 3000, 60 s bars,
    all costs 0, taker, no short, no stop / take profit / hold / mask).
    Tests override what they exercise."""
    o = dict(capital=6000, order_amount=3000, bar_seconds=60,
             costs=dict(taker_fee_pct=0, maker_fee_pct=0, slippage_pct=0, spread_pct=0),
             execution="taker", maker_timeout_bars=None, allow_short=False, swap_daily_pct=0,
             stop_loss_pct=None, take_profit_pct=None, max_hold_bars=None, exit_execution="signal",
             maker_tp_pct=None, entry_mask=None, entry_sides="both", stop_mode="fixed",
             stop_window_bars=None,
             undecided=dict(wick_short_history="refuse", same_side_exit_signal="keep"))
    if "costs" in kw:
        c = dict(o["costs"]); c.update(kw.pop("costs")); o["costs"] = c
    if "undecided" in kw:
        u = dict(o["undecided"]); u.update(kw.pop("undecided")); o["undecided"] = u
    o.update(kw)
    return o


def run(bars, sigs, **kw):
    return run_bars(bars, sigs, opts(**kw))


def fills(r):
    """(bar, side, price, size) of every fill, exact."""
    return [(f.bar, f.side, f.price, f.size) for f in r.fills]


def fbs(r):
    """(bar, side, price) of every fill, exact."""
    return [(f.bar, f.side, f.price) for f in r.fills]


def close_to(a, b, rel=F(1, 10 ** 9)):
    a, b = F(a), F(str(b)) if isinstance(b, float) else F(b)
    return abs(a - b) <= rel * max(1, abs(a), abs(b))


