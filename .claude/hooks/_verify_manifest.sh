#!/bin/sh
# 指紋の照合。**両方の関門の先頭で走らせる。**
# 2026-09-13 の監査の指摘: 旧版は push 系以外を先に exit 0 で落としてから照合していたため、
# Write・Edit・Agent・Stop(返答)のときは一度も照合されなかった。
# 「食い違えば全操作を拒否」という報告は事実と違っていた。
cd "${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}" 2>/dev/null || exit 0

# **復旧路は必ず開けておく。**
# 2026-09-13 の実測: 照合を全操作に広げた直後、フック自身の指紋が変わって
# **復旧手順(再生成スクリプト)まで拒否され、関門が自分自身を直せなくなった。**
# 監査役はこれを事前に予言していた(「この状態の自然な回避策は台帳かフックを自分で触ることであり、
# オーナーが今回禁じたまさにその行動へリードを追い込む形になっている」)。
# 再生成は指紋を現物に合わせるだけで、改変そのものはコミットの差分に残る。
case "$1" in --allow-regen) exit 0 ;; esac

M="docs/AUDITOR/HOOK_MANIFEST.sha256"
[ -f "$M" ] || exit 0
BAD="$(while read -r h f; do
  [ -n "$h" ] || continue
  [ -f "$f" ] || { printf '%s(消失) ' "$f"; continue; }
  [ "$(sha256sum "$f" | cut -d' ' -f1)" = "$h" ] || printf '%s ' "$f"
done < "$M")"
[ -z "$BAD" ] && exit 0
cat >&2 <<EOM
[関門] 操作を拒否した。**フック・設定・監査役の定義が、台帳の指紋と食い違っている。**

食い違ったファイル: ${BAD}

オーナー逐語(2026-09-13、L-156):
「**なんでフックを自分で書き換える前提で話してる？私が指示した時以外変えないものでないと
フックの意味をなさない。**」

**これらはオーナーの指示があったときだけ変更する。**変更した場合は同じコミットで
  (a) docs/OWNER_LOG.md に指示の逐語を記録
  (b) sh scripts/regen_hook_manifest.sh
**指示が無いなら元に戻すこと。**

**注意(2026-09-13 の監査による事実の訂正)**: この検査はリードの改竄を**防がない**。
リードは台帳もフックも同じコミットで書き換えられる。**この検査がしているのは
「改竄がコミットの差分に残る」ことと「食い違ったまま操作できない」ことだけである。**
EOM
exit 2
