#!/bin/sh
# 「押し出そうとしている範囲に、監査の記録が入っているか」だけを判定する共有部品。
#
# **なぜ切り出したか(2026-09-13、5 本目の監査の指摘)**:
# 判定の抽出が、行動の関門では「**行頭の判定のうち最後のもの**」、返答の関門では「最初のもの」と
# **非対称**になっていた。「同じ種類の穴を一方だけ塞いで他方は塞がない」ことへの指摘。
# → 押し出し側の判定はこの 1 本に集約し、Bash の関門と git の pre-push の両方から呼ぶ。
#
# 使い方: sh _require_action_audit.sh [<範囲>]
#   範囲を省いたら @{u}..HEAD(上流が無ければ HEAD~1..HEAD)。
#   通す = exit 0 / 通さない = exit 2(理由は標準エラーへ)。

cd "${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}" 2>/dev/null || exit 2

LOG="docs/AUDITOR/ACTION_LOG.md"
RANGE="$1"

if [ -z "$RANGE" ]; then
  if UPSTREAM="$(git rev-parse --abbrev-ref --symbolic-full-name '@{u}' 2>/dev/null)" && [ -n "$UPSTREAM" ]; then
    RANGE="$UPSTREAM..HEAD"
  else
    RANGE="HEAD~1..HEAD"
  fi
fi

CHANGED="$(git diff --name-only "$RANGE" 2>/dev/null)"

# 範囲が取れない = 判定できない。**判定できないときは通さない。**
if [ -z "$CHANGED" ] && ! git rev-parse "$RANGE" >/dev/null 2>&1; then
  cat >&2 <<EOF
[行動監査の関門] 押し出しを拒否した。

理由: 押し出そうとしている範囲($RANGE)を判定できなかった。**判定できないときは通さない。**
(2026-09-13 の教訓: 判定できないものを「たぶん大丈夫」で通すのが、この体制の失敗の型)
EOF
  exit 2
fi

if ! printf '%s\n' "$CHANGED" | grep -qx "$LOG"; then
  cat >&2 <<EOF
[行動監査の関門] 押し出しを拒否した。

理由: この押し出しに含まれるコミット($RANGE)に $LOG の追記が無い。

規則(CLAUDE.md §8): 納品物は監査役を通さずにオーナーへ出さない。
2026-09-13、リードは押し出しの直前の「監査役を通したか」という**表示**を見たうえで押し出した。
だからこの関門は表示ではなく拒否する。

通すには、次を満たしてから commit し直すこと:

  1. \`owner-model-auditor\` を呼ぶ。渡すのは
       (a) これからやろうとしている一手
       (b) それが応えているオーナーの逐語(引用と出典)
  2. 返ってきた「判定: 通す / 止める」と、指摘と、その処置を $LOG に追記する
  3. **「止める」が残っている間は押し出さない。**直すか、両論を添えてオーナーへ上申する
     (監査役の「止める」をリードが単独で退けることはできない = L-112)
EOF
  exit 2
fi

# ログが触られただけでは通さない。今回の範囲の追記に、監査が実際に走った形跡
# (監査役の名前 + 判定行 + 指摘の本文)が含まれることを要求する。
ADDED="$(git diff "$RANGE" -- "$LOG" 2>/dev/null | grep '^+' | grep -v '^+++')"
MISS=""
printf '%s' "$ADDED" | grep -q 'owner-model-auditor' || MISS="${MISS} 監査役の名前"

# **判定は「行頭が `判定:` の行」のうち最後のものだけを見る。**
# 行頭に限るのは、地の文の中の引用(例:「リードが自分で『判定: 通す』と書けば通る」)を
# 判定として拾わないため。2026-09-13 の 2 回目の監査で、まさにそれが起きた
# (**止まらないと書いた文章そのものが、止まらない鍵になっていた**)。
VERDICT_LINE="$(printf '%s\n' "$ADDED" | grep '^+判定:' | tail -1)"
if [ -z "$VERDICT_LINE" ]; then
  MISS="${MISS} 行頭の「判定:」の行"
else
  case "$VERDICT_LINE" in
    "+判定: 通す"*) ;;
    *) MISS="${MISS} 最後の判定が [${VERDICT_LINE#+}] (行頭の判定が「判定: 通す」でなければ押し出さない)" ;;
  esac
fi

# 指摘の本文が 8 行以上(見出しだけの空の追記を弾く)
[ "$(printf '%s' "$ADDED" | wc -l)" -ge 8 ] || MISS="${MISS} 指摘の本文"

# --- 抜き取り(2026-09-13、L-164)---
# 返答 1 件ずつの関門は撤去した(空回りしていた。§0.1 の対応表が代わり)。
# 代わりに **1 日 1 件だけ**、その日の返答を無作為に選んで監査し、守れているかを測る。
# **「止める」が出たら翌日は返答の全件監査に戻す。**これが無いと A-17(記録するだけ)になる。
# 押し出しのときに確かめるのは、押し出しが 1 日の仕事の区切りだからである。
# **日付は UTC で取る。**最初 JST にしたが、`OWNER_LOG` も `ACTION_LOG` も
# **この環境の日付(UTC)で採番されている**ので、JST だと日付が 1 日ずれて
# 「本日の抜き取りが無い」と誤判定する(2026-09-13 に実測。JST は既に 09-14 だった)。
# オーナーに見せる時刻は JST、台帳の日付は UTC、と使い分ける。
TODAY="$(date -u +%Y-%m-%d)"
# **マーカーの行だけでは通さない(2026-09-13、11 本目の監査)。**
# 旧版は `抜き取り: <日付>` の行があるかしか見ておらず、**その 1 行を足すだけで
# (監査を回さず、判定も書かずに)検査を満たせた**。行動監査の側では「監査役の名前 +
# 判定 + 本文 8 行」を要求しているのに、抜き取りの側だけ素通りだった。
# **同じ種類の穴を一方だけ塞ぐ**という、5 本目の監査が指摘した型そのもの。
# **節は次の `## ` で確実に切る(2026-09-13、12 本目の監査)。**
# 旧版は 3 つの規則を同じ行に順番に当てる形で、見出しに当たっても `f` が 0 に戻らず
# `f{print}` が走り続けたため、**次の見出し 1 個分の節を丸ごと吸い込んでいた**(実物で再現)。
# その結果、**別の節にある監査役の名前・判定・本文が、今日の抜き取りの中身として数えられた**。
# 検査を足すたびに隣へ穴が移る、という 09-13 に繰り返した型そのもの。
SAMPLE_SEC="$(awk -v k="抜き取り: $TODAY" '
  index($0,k){f=1}
  f && /^## /{exit}
  f{print}' "$LOG" 2>/dev/null)"
if [ -z "$SAMPLE_SEC" ]; then
  MISS="${MISS} 本日($TODAY)の抜き取り監査"
else
  printf '%s' "$SAMPLE_SEC" | grep -q 'owner-model-auditor'     || MISS="${MISS} 本日の抜き取りに監査役の名前"
  printf '%s\n' "$SAMPLE_SEC" | grep -q '^抜き取り判定:'     || MISS="${MISS} 本日の抜き取りの行頭「抜き取り判定:」"
  [ "$(printf '%s' "$SAMPLE_SEC" | grep -c '')" -ge 8 ]     || MISS="${MISS} 本日の抜き取りの本文(8 行以上)"
fi

# **戻し条件を機械にする(2026-09-13、10 本目の監査)。**
# 指摘: 「止めるが出たら翌日は全件に戻す」は**リードの約束であって機械ではなかった**。
# §0.1 が「リードの自覚に依存する仕組みは機能しない」と書いた直後に、同じ形で書いていた。
# → **最後の抜き取りの判定が「止める」なら、返答の全件関門(Stop)が配線されていることを要求する。**
# 節は**次の見出し(`## `)で切る**。切らないと、抜き取りの後ろに並ぶ別の監査の
# 「判定: 通す」を抜き取りの判定として拾ってしまう(2 本目の監査が押し出し側で見つけた型)。
# **抜き取りの判定は `抜き取り判定:` という別の語で書く(2026-09-13、リードが実測で発見)。**
# 同じ `判定:` を使っていたため、**抜き取りの「通す」が、直前の行動監査の「止める」を
# 上書きして押し出しが通る**状態になっていた(この関門は追記の中の最後の `判定:` を見るため)。
# 語を分けることで、行動監査の判定と抜き取りの判定が混ざらない。
LAST_SAMPLE_VERDICT="$(awk '
  /^抜き取り: /{f=1; v=""; next}
  f && /^## /{f=0}
  f && /^抜き取り判定:/{v=$0}
  END{print v}' "$LOG" 2>/dev/null)"
case "$LAST_SAMPLE_VERDICT" in
  "抜き取り判定: 止める"*)
    if ! grep -q 'reply_audit_gate.sh' .claude/settings.json 2>/dev/null \
       || ! python3 - <<'PY' 2>/dev/null
import json,sys
d=json.load(open(".claude/settings.json"))
wired=any("reply_audit_gate.sh" in h.get("command","")
          for g in d.get("hooks",{}).get("Stop",[]) for h in g.get("hooks",[]))
sys.exit(0 if wired else 1)
PY
    then
      MISS="${MISS} 返答の全件監査への復帰(最後の抜き取りが「止める」だった。settings.json の Stop に reply_audit_gate.sh を戻すこと)"
    fi ;;
esac

[ -z "$MISS" ] && exit 0

cat >&2 <<EOF
[行動監査の関門] 押し出しを拒否した。

理由: $LOG は変更されているが、監査が実際に走った形跡が足りない。
不足:${MISS}

**これは「記録を省いて通すための空の追記」を弾く判定である**
(オーナー指摘 2026-09-13:「指摘の件数を上げるだけの意味のないものになっています」)。

**判定はリードが書くものではない。**オーナー逐語(2026-09-13):
「**判定をあなたが書かなければいい。監査の判定をそのまま書いてそれに従え**」
→ 監査役が返した 3 行(オーナーの負荷 / 品質 / 判定)を**逐語で転記**すること。
書き換え・要約・自分の判断での上書きをしない。
EOF
exit 2
